import { and, eq, gte, inArray, isNotNull, lt } from "drizzle-orm";
import { db } from "@/db";
import { members, scheduleBlocks, sessions } from "@/db/schema";
import type { SessionPayload } from "@/lib/session";
import { slotStartHour } from "@/lib/coach-life/timetable";

const HORIZON_DAYS = 14;

function nextOccurrences(dow: number, hour: number, from: Date, days: number) {
  const out: Date[] = [];
  const cursor = new Date(from);
  cursor.setHours(0, 0, 0, 0);
  for (let i = 0; i < days; i++) {
    const day = new Date(cursor);
    day.setDate(cursor.getDate() + i);
    if (day.getDay() !== dow) continue;
    day.setHours(hour, 0, 0, 0);
    if (day > from) out.push(day);
  }
  return out;
}

/**
 * Ensure every client block on the trainer's weekly timetable has a real session
 * booked for each occurrence in the next two weeks. Idempotent.
 */
export async function syncRhythmSessions(session: SessionPayload) {
  const blocks = await db
    .select({
      dayOfWeek: scheduleBlocks.dayOfWeek,
      timeSlot: scheduleBlocks.timeSlot,
      memberId: scheduleBlocks.memberId,
      centreId: members.centreId,
    })
    .from(scheduleBlocks)
    .innerJoin(members, eq(scheduleBlocks.memberId, members.id))
    .where(
      and(
        eq(scheduleBlocks.trainerId, session.userId),
        eq(scheduleBlocks.organisationId, session.organisationId),
        eq(scheduleBlocks.blockType, "client"),
        isNotNull(scheduleBlocks.memberId),
        eq(members.status, "active"),
      ),
    );
  if (blocks.length === 0) return { created: 0 };

  const now = new Date();
  const horizon = new Date(now);
  horizon.setDate(horizon.getDate() + HORIZON_DAYS);

  const existing = await db
    .select({ memberId: sessions.memberId, scheduledAt: sessions.scheduledAt })
    .from(sessions)
    .where(
      and(
        eq(sessions.trainerId, session.userId),
        gte(sessions.scheduledAt, now),
        lt(sessions.scheduledAt, horizon),
      ),
    );
  const taken = new Set(existing.map((s) => `${s.memberId}|${s.scheduledAt.getTime()}`));

  const rows: (typeof sessions.$inferInsert)[] = [];
  for (const block of blocks) {
    const hour = slotStartHour(block.timeSlot);
    if (hour == null || !block.memberId) continue;
    for (const when of nextOccurrences(block.dayOfWeek, hour, now, HORIZON_DAYS)) {
      const key = `${block.memberId}|${when.getTime()}`;
      if (taken.has(key)) continue;
      taken.add(key);
      rows.push({
        organisationId: session.organisationId,
        centreId: block.centreId,
        memberId: block.memberId,
        trainerId: session.userId,
        kind: "pt",
        status: "scheduled",
        scheduledAt: when,
      });
    }
  }

  if (rows.length > 0) await db.insert(sessions).values(rows);
  return { created: rows.length };
}

/** Cancel future, untouched sessions that were generated by a removed client block. */
export async function releaseRhythmSessions(
  session: SessionPayload,
  block: { dayOfWeek: number; timeSlot: string; memberId: string | null },
) {
  const hour = slotStartHour(block.timeSlot);
  if (!block.memberId || hour == null) return { cancelled: 0 };

  const now = new Date();
  const upcoming = await db
    .select({ id: sessions.id, scheduledAt: sessions.scheduledAt })
    .from(sessions)
    .where(
      and(
        eq(sessions.trainerId, session.userId),
        eq(sessions.memberId, block.memberId),
        eq(sessions.status, "scheduled"),
        gte(sessions.scheduledAt, now),
      ),
    );

  const ids = upcoming
    .filter(
      (s) =>
        s.scheduledAt.getDay() === block.dayOfWeek &&
        s.scheduledAt.getHours() === hour &&
        s.scheduledAt.getMinutes() === 0,
    )
    .map((s) => s.id);

  if (ids.length > 0) {
    await db.update(sessions).set({ status: "cancelled" }).where(inArray(sessions.id, ids));
  }
  return { cancelled: ids.length };
}
